def main() -> None:
    copied = copy_from_kit(TASK, KIT_FILES)
    write_list()
    (TASKS / TASK / f"{TASK}.yaml").write_text(TEMPLATE.replace("@CELLS@", cell_items()), encoding="utf-8")
    print(f"{TASK}: {len(copied)} kit files ({sum(p.stat().st_size for p in copied) / 1e6:.2f} MB), stimuli.csv, {TASK}.yaml")


if __name__ == "__main__":
    main()

"""Write the operational adaptation of the Navon task (edge/library/tasks/navon_ops/: experiment, trial list, pictures).

    python tools/library/make_navon_ops.py

The compound letters of the classic task become a FORMATION of track symbols: a big (global) shape made of small
(local) symbols. The two shapes are frame shapes of the symbology convention, one for each key: a DIAMOND (H key;
the hostile frame) and a SQUARE (S key). The formation is a diamond outline or a square outline on a 7 x 7 grid;
each local symbol is a small diamond or square drawn by a shape item, all in one colour, so only the shape tells
them apart. Consistent: the same shape at both levels; inconsistent: different shapes. Only the 20 grid places
that either outline uses have an item; the trial list's `cells` (49 characters, x = a symbol there) says which are
on. As in make_navon.py this script writes the experiment file too (the 20 cell items), and the kit pictures:
  c2   the formation on a radar-style plot, symbols in the console accent colour
  uav  the formation in a camera frame inside the corner-bracket reticle, symbols as amber candidate markers
"""

from __future__ import annotations

import csv

from kit_copy import TASKS, copy_from_kit

TASK = "navon_ops"
KIT_FILES = ["backgrounds/plot_radar_1280x720.png", "terrain/terrain_02_village.jpg", "reticles/reticle_brackets.png"]
PATTERNS = {   # 7 x 7, rows top to bottom
    "diamond": ["0001000", "0010100", "0100010", "1000001", "0100010", "0010100", "0001000"],
    "square": ["0000000", "0111110", "0100010", "0100010", "0100010", "0111110", "0000000"],
}
KEY = {"diamond": "h", "square": "s"}
SPACING = 36           # px between grid places


def cells(shape: str) -> str:
    return "".join(PATTERNS[shape]).replace("1", "x").replace("0", ".")


def used() -> list[int]:
    return [i for i in range(49) if any(cells(s)[i] == "x" for s in PATTERNS)]


def write_list() -> None:
    with (TASKS / TASK / "stimuli.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["global_shape", "local_shape", "cells", "consistency", "global_key", "local_key"])
        for g in PATTERNS:
            for loc in PATTERNS:
                w.writerow([g, loc, cells(g), "consistent" if g == loc else "inconsistent", KEY[g], KEY[loc]])


def cell_items() -> str:
    out = []
    for i in used():
        r, c = divmod(i, 7)
        x, y = (c - 3) * SPACING, (3 - r) * SPACING
        out.append(f"      - {{id: c{i:02d}, type: shape, shape: rect, size: $local_size, ori: $local_ori, fill: transparent, "
                   f"line_color: \"$looks[theme]['colour']\", line_width: 3, pos: [{x}, {y}], "
                   f"if: \"$cells[{i}] == 'x'\", start: 0.5, save: false}}")
    return "\n".join(out)



"""Write the Navon task of the EDGE task library (experiment file and trial list).

    python tools/library/make_navon.py

The compound letters are drawn as a 5 x 5 grid of small letters: 25 text items, one per grid cell, each
showing the small (local) letter when the trial's `cells` pattern has an x at its place
(written with x and . so the trial list keeps it as text), else nothing.
This keeps the shape exact in every display (no dependence on a monospaced font). Global and local
letters are H and S: consistent (H of Hs, S of Ss) and inconsistent (H of Ss, S of Hs) stimuli.
"""

from __future__ import annotations

import csv
from pathlib import Path

FOLDER = Path(__file__).resolve().parents[2] / "edge" / "library" / "tasks" / "navon"

PATTERNS = {   # rows top to bottom
    "H": ["10001", "10001", "11111", "10001", "10001"],
    "S": ["11111", "10000", "11111", "00001", "11111"],
}
SPACING = 34          # px between grid cells
LOCAL_HEIGHT = 30     # px, size of the small letters


def write_list() -> None:
    with (FOLDER / "stimuli.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["global_letter", "local_letter", "cells", "consistency", "global_key", "local_key"])
        for g in PATTERNS:
            for loc in PATTERNS:
                w.writerow([g, loc, "".join(PATTERNS[g]).replace("1", "x").replace("0", "."), "consistent" if g == loc else "inconsistent",
                            g.lower(), loc.lower()])


def cell_items() -> str:
    out = []
    for i in range(25):
        r, c = divmod(i, 5)
        x, y = (c - 2) * SPACING, (2 - r) * SPACING
        out.append(f"      - {{id: c{i:02d}, type: text, text: \"$local_letter if cells[{i}] == 'x' else ''\", "
                   f"height: {LOCAL_HEIGHT}, bold: true, pos: [{x}, {y}], start: 0.5, save: false}}")
    return "\n".join(out)


TEMPLATE = """\
# Generated by tools/library/make_navon.py: edit the generator (or this file, if you don't regenerate it).
name: navon
description: >
  Navon global/local task. A large letter (H or S) is made of small letters (H or S). In the global block
  the participant names the LARGE letter, in the local block the SMALL letters (H key or S key).
  Consistent stimuli have the same letter at both levels, inconsistent ones different letters.
  The block order is counterbalanced by participant number.

settings:
  window: {size: [1280, 720], background: "#000000", units: px}
  participant: {participant: "001", session: "1"}

measures:
  - {id: rt, label: Reaction time (correct trials), role: outcome, column: resp.rt, trials: $resp.corr == 1,
     loop: trials, summary: median, units: s, expect: [0.25, 2.0]}
  - {id: accuracy, label: Accuracy, role: outcome, column: resp.corr, loop: trials, summary: proportion}
  - {id: level, label: Attend to the large (global) or small (local) letter, role: factor, column: level}
  - {id: consistency, label: Same or different letter at both levels, role: factor, column: consistency}

routines:
  instructions:
    components:
      - id: text
        type: text
        text: |
          BIG AND SMALL LETTERS

          You will see a big letter that is made of small letters,
          for example a big H made of small S's.

          The letters are always H or S. Press the H key for H and the S key for S.

          There are two parts. In one you answer the BIG letter, in the other the SMALL letters.
          Before each part you are told which one, and you can practise.

          Keep your eyes on the centre. Press SPACE to continue.
        height: 26
        wrap_width: 1100
      - {id: go, type: keyboard, keys: [space], end_routine: true}

  block_intro:
    components:
      - {id: text, type: text, text: $instruction, height: 28, wrap_width: 1100}
      - {id: go, type: keyboard, keys: [space], end_routine: true}

  trial:
    components:
      - {id: fix, type: fixation, duration: 0.5, size: 30}
@CELLS@
      - id: onset
        type: marker
        label: $f"navon_{level}_{consistency}"
        start: 0.5
      - id: resp
        type: keyboard
        keys: [h, s]
        start: 0.5
        duration: 2.0
        correct: "$global_key if level == 'global' else local_key"
        end_routine: true

  feedback:
    duration: 0.8
    components:
      - id: fb
        type: text
        text: "$'Correct' if resp.corr == 1 else ('Too slow' if resp.keys is None else 'Wrong')"
        color: "$'#55dd55' if resp.corr == 1 else '#ff5555'"
        height: 40

  ready:
    components:
      - id: text
        type: text
        text: "$f'Practice finished. Now the test part: answer the {level_word} letter.  Press SPACE to start.'"
        height: 28
        wrap_width: 1100
      - {id: go, type: keyboard, keys: [space], end_routine: true}

  thanks:
    duration: 3
    components:
      - {id: bye, type: text, text: "Thank you! This task is finished.", height: 34}

flow:
  - instructions
  - loop: blocks
    order: counterbalance
    conditions:
      - level: global
        level_word: BIG
        instruction: |
          PART: THE BIG LETTER

          Answer the BIG letter and ignore the small letters it is made of.
          H key = big H        S key = big S

          Press SPACE to practise.
      - level: local
        level_word: SMALL
        instruction: |
          PART: THE SMALL LETTERS

          Answer the SMALL letters and ignore the big letter they form.
          H key = small H's        S key = small S's

          Press SPACE to practise.
    children:
      - block_intro
      - loop: practice
        conditions: stimuli.csv
        order: random
        repeats: 2
        children: [trial, feedback]
      - ready
      - loop: trials
        conditions: stimuli.csv
        order: random
        repeats: 12
        max_repeat: {global_letter: 4, local_letter: 4}
        children:
          - trial
          - {routine: feedback, if: "$resp.corr != 1"}
  - thanks
"""


def main() -> None:
    FOLDER.mkdir(parents=True, exist_ok=True)
    write_list()
    (FOLDER / "navon.yaml").write_text(TEMPLATE.replace("@CELLS@", cell_items()), encoding="utf-8")
    print("wrote", FOLDER)


if __name__ == "__main__":
    main()
